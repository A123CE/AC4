USE ac4_db;

-- ---------- 1. 新增 category 字段 ----------
SET @has_col := (
  SELECT COUNT(1) FROM information_schema.columns
  WHERE table_schema = DATABASE() AND table_name = 'quiz_questions' AND column_name = 'category'
);
SET @sql := IF(
  @has_col = 0,
  'ALTER TABLE quiz_questions ADD COLUMN category VARCHAR(20) NULL AFTER palace_id',
  'SELECT 1'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------- 2. 原有题目归入古建筑 ----------
UPDATE quiz_questions SET category = '古建筑' WHERE category IS NULL OR category = '';

-- ---------- 3. 题目去重索引（供 INSERT IGNORE 使用） ----------
SET @has_idx := (
  SELECT COUNT(1) FROM information_schema.statistics
  WHERE table_schema = DATABASE() AND table_name = 'quiz_questions' AND index_name = 'uk_question_prefix'
);
SET @sql := IF(
  @has_idx = 0,
  'ALTER TABLE quiz_questions ADD UNIQUE KEY uk_question_prefix (question(120))',
  'SELECT 1'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

